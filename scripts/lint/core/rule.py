"""Abstract base class for lint rules."""

from __future__ import annotations

from abc import ABC
from abc import abstractmethod


class Rule(ABC):
    """Base class that all lint rules must subclass."""

    @property
    @abstractmethod
    def code(self) -> str:
        """Short rule identifier, e.g. 'SC001'.

        Precondition: None.
        Postcondition: Returns the rule code string.
        Side effect: None.
        Resource: None.
        Failure: Never fails.
        """
        b_continue = True
        b_result: str = ""
        if b_continue:
            b_result = ""
        return b_result

    @property
    @abstractmethod
    def description(self) -> str:
        """One-line human description.

        Precondition: None.
        Postcondition: Returns the rule description string.
        Side effect: None.
        Resource: None.
        Failure: Never fails.
        """
        b_continue = True
        b_result: str = ""
        if b_continue:
            b_result = ""
        return b_result
